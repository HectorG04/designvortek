/**
 * combine-cover-prompt-batches.mjs
 *
 * Merges docs/seo/all-covers/batch-NN.md (8 files) into a single
 * docs/seo/all-cover-prompts.md, in batch order. Then run
 * `node scripts/build-raw-prompts.mjs docs/seo/all-cover-prompts.md`
 * to extract the one-per-line raw txt.
 *
 * Also runs a banned-word audit and a count sanity check across the
 * combined output.
 */

import { readFileSync, writeFileSync, readdirSync, existsSync, statSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const BATCHES_DIR = join(ROOT, 'docs', 'seo', 'all-covers')
const OUT = join(ROOT, 'docs', 'seo', 'all-cover-prompts.md')

const batchFiles = readdirSync(BATCHES_DIR)
  .filter((f) => /^batch-\d+\.md$/.test(f))
  .sort()

console.log(`Found ${batchFiles.length} batch files.`)
if (batchFiles.length !== 8) {
  console.warn(`  WARN: expected 8, got ${batchFiles.length}`)
}

const parts = [
  '# Design Vortex — All Cover Image Prompts (94 posts)',
  '',
  '> Generated by 8 parallel agents. Each batch handles ~12 posts with a 10-approach variety rotation (Workspace, Object, Environment, Palette, Comparison, Documents, Tool, Abstract, Atmosphere, Character — last one capped at ≤2 per batch).',
  '',
  '> **Digital-studio vocabulary only.** No oil/canvas/easel/sable/linseed/pigment/hand-painted/hand-drawn references anywhere.',
  '',
  '> One fenced code block per post. Use `node scripts/build-raw-prompts.mjs docs/seo/all-cover-prompts.md` to extract a raw one-per-line txt for feeding into a generator queue.',
  '',
  '---',
  '',
]

for (const f of batchFiles) {
  const path = join(BATCHES_DIR, f)
  const content = readFileSync(path, 'utf8')
  parts.push(content.trim())
  parts.push('')
  parts.push('---')
  parts.push('')
}

writeFileSync(OUT, parts.join('\n'), 'utf8')
const sizeKB = Math.round(statSync(OUT).size / 1024)
console.log(`Wrote combined file: ${OUT.replace(ROOT, '.')}  (${sizeKB} KB)`)

// Count fenced blocks (each one is a prompt)
const combined = readFileSync(OUT, 'utf8')
const blockCount = (combined.match(/```\n[\s\S]*?\n```/g) || []).length
console.log(`Fenced prompt blocks found: ${blockCount}`)

// Banned-word audit
const BANNED = [
  'oil paint', 'oil painting', 'linseed', 'sable brush', 'easel',
  'palette knife', 'wet paint', 'paint tube', 'brush jar', 'gesso',
  'hand-painted', 'hand painted', 'hand-drawn', 'hand drawn',
  'alizarin', 'cadmium red', 'cadmium yellow', 'titanium white',
  'lead white', 'burnt umber', 'raw umber',
]
console.log('\n=== Banned-word audit ===')
let issues = 0
for (const term of BANNED) {
  const re = new RegExp('\\b' + term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\b', 'gi')
  const matches = combined.match(re)
  if (matches) {
    console.log(`  ❌ "${term}" × ${matches.length}`)
    issues++
  }
}
if (issues === 0) console.log('  ✅ No banned terms found.')
